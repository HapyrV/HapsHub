// Builds the World Map's country shapes from world-atlas's countries-110m.json (TopoJSON).
//   npm pack world-atlas@2.0.2, unpack it, then:  node tools/hapshub/make-world-data.mjs <path to countries-110m.json>
// Writes frontend/modules/tools/world-map/world-data.js: each country's name, two-letter code, a point to put its
// pin on, and its outline as flat [lon, lat, lon, lat, ...] rings rounded to 0.1 degree.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const source = process.argv[2];
if (!source) { console.log('usage: node tools/hapshub/make-world-data.mjs <countries-110m.json>'); process.exit(2); }
const topo = JSON.parse(readFileSync(source, 'utf8'));
const { scale, translate } = topo.transform;

// Arcs are stored as quantized, delta-encoded points.
const arcs = topo.arcs.map(arc => {
    let x = 0, y = 0;
    return arc.map(([dx, dy]) => { x += dx; y += dy; return [x * scale[0] + translate[0], y * scale[1] + translate[1]]; });
});
const ring = indexes => {
    const points = [];
    for (const index of indexes) {
        const arc = index < 0 ? [...arcs[~index]].reverse() : arcs[index];
        points.push(...(points.length ? arc.slice(1) : arc));
    }
    return points;
};
const area = points => points.reduce((sum, [x1, y1], i) => { const [x2, y2] = points[(i + 1) % points.length]; return sum + x1 * y2 - x2 * y1; }, 0) / 2;
const centroid = points => {
    let a = 0, cx = 0, cy = 0;
    points.forEach(([x1, y1], i) => { const [x2, y2] = points[(i + 1) % points.length]; const f = x1 * y2 - x2 * y1; a += f; cx += (x1 + x2) * f; cy += (y1 + y2) * f; });
    return a ? [cx / (3 * a), cy / (3 * a)] : points[0];
};

// Two-letter codes: every code the system knows a name for, matched to world-atlas's names.
const names = new Intl.DisplayNames(['en'], { type: 'region' });
const byName = new Map();
const RETIRED = new Set(['AN', 'BU', 'CS', 'DD', 'EU', 'EZ', 'FX', 'NT', 'QO', 'SU', 'TP', 'UN', 'XA', 'XB', 'YD', 'YU', 'ZR', 'ZZ']);
for (let a = 65; a <= 90; a++) for (let b = 65; b <= 90; b++) {
    const code = String.fromCharCode(a, b);
    let name;
    try { name = names.of(code); } catch { continue; }
    // Old and made-up codes share names with today's countries (DD and DE are both Germany).
    if (RETIRED.has(code)) continue;
    if (name && name !== code && !byName.has(name.toLowerCase())) byName.set(name.toLowerCase(), code);
}
const aliases = {
    'United States of America': 'US', 'Dem. Rep. Congo': 'CD', 'Congo': 'CG', 'Central African Rep.': 'CF', 'S. Sudan': 'SS',
    'Dominican Rep.': 'DO', 'Eq. Guinea': 'GQ', 'eSwatini': 'SZ', 'Bosnia and Herz.': 'BA', 'Macedonia': 'MK', 'North Macedonia': 'MK',
    'Solomon Is.': 'SB', 'Falkland Is.': 'FK', 'Fr. S. Antarctic Lands': 'TF', 'W. Sahara': 'EH', "Côte d'Ivoire": 'CI',
    'Czechia': 'CZ', 'Timor-Leste': 'TL', 'N. Cyprus': null, 'Trinidad and Tobago': 'TT', 'Somaliland': null, 'Kosovo': 'XK', 'Palestine': 'PS',
    'Myanmar': 'MM', 'Taiwan': 'TW', 'Turkey': 'TR', 'Russia': 'RU', 'South Korea': 'KR', 'North Korea': 'KP', 'Laos': 'LA',
    'Vietnam': 'VN', 'Syria': 'SY', 'Iran': 'IR', 'Brunei': 'BN', 'Moldova': 'MD', 'Tanzania': 'TZ', 'Bolivia': 'BO',
    'Venezuela': 'VE', 'Antarctica': 'AQ', 'Greenland': 'GL', 'Puerto Rico': 'PR', 'New Caledonia': 'NC', 'Vanuatu': 'VU',
};
const countries = [];
const unmatched = [];
for (const geometry of topo.objects.countries.geometries) {
    const name = geometry.properties?.name || '';
    const polygons = geometry.type === 'Polygon' ? [geometry.arcs] : geometry.type === 'MultiPolygon' ? geometry.arcs : [];
    const rings = polygons.flatMap(polygon => polygon.map(ring));
    if (!rings.length) continue;
    const code = name in aliases ? aliases[name] : byName.get(name.toLowerCase()) ?? null;
    if (code === undefined || (code === null && !(name in aliases))) unmatched.push(name);
    const largest = rings.reduce((best, r) => Math.abs(area(r)) > Math.abs(area(best)) ? r : best, rings[0]);
    // Russia's mainland runs past 180 degrees, which pulls its middle into the Pacific; it gets a fixed point.
    const labels = { RU: [96, 62], FJ: [178, -17.8] };
    let [lon, lat] = labels[code] || centroid(largest);
    if (lon > 180) lon -= 360;
    const round = v => Math.round(v * 10) / 10;
    countries.push({ n: name, c: code, p: [round(lon), round(lat)], r: rings.map(r => r.flatMap(([x, y]) => [round(x), round(y)])) });
}
const out = join(ROOT, 'frontend', 'modules', 'tools', 'world-map', 'world-data.js');
writeFileSync(out, `// Generated by tools/hapshub/make-world-data.mjs from world-atlas 2.0.2 (ISC licence, Mike Bostock),\n`
    + `// which is made from Natural Earth's public domain 1:110m countries. Do not edit by hand.\n`
    + `const HUB_WORLD_COUNTRIES = ${JSON.stringify(countries)};\n`);
console.log(`${countries.length} countries written to ${out}`);
if (unmatched.length) console.log(`no code for: ${unmatched.join(', ')}`);
